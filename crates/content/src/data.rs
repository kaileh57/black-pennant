//! Layout (all CC BY 4.0):
//! - `crates/content/data/parts/actN.ron`            `Vec<PartDef>`          units `data-parts-*`
//! - `crates/content/data/weapons.ron`               `WeaponTables`          unit `data-weapons`
//! - `crates/content/data/materials.ron`             `Vec<MaterialDef>`      unit `data-weapons`
//! - `crates/content/data/tuning.ron`                `TuningTable`           unit `data-tuning`
//! - `crates/content/data/campaign_rules.ron`        `CampaignRules`         unit `data-tuning`
//! - `crates/content/data/difficulty.ron`            `Vec<DifficultyPreset>` unit `data-tuning`
//! - `crates/content/data/rulesets.ron`              `Vec<(String, Ruleset)>` unit `data-tuning`
//! - `crates/content/data/theatre.ron`               `TheatreDef`            unit `data-theatre`
//! - `crates/content/data/acts.ron`                  `Vec<ActDef>`           unit `data-theatre`
//! - `crates/content/data/enemy_classes/actN.ron`    `Vec<EnemyClassDef>`    units `data-enemy-*`
//! - `crates/content/data/fleets/actN.ron`           `Vec<FleetTemplate>`    units `data-enemy-*`
//! - `crates/content/data/operations/actN.ron`       `Vec<OperationDef>`     units `data-operations-*`
//! - `crates/content/data/aces.ron`                  `Vec<AceDef>`           unit `data-aces-cards`
//! - `crates/content/data/doctrine_cards.ron`        `Vec<DoctrineCardDef>`  unit `data-aces-cards`
//! - `blueprints/**/*.bp.ron`, `blueprints/**/*.kit.ron`  stock ships and kits, collected by `build.rs`
//!
//! Adding a stock blueprint or kit needs no Rust change: `build.rs` scans `blueprints/` in sorted order.
