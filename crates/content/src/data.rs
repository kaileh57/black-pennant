/// Stock blueprints and kits found under `blueprints/` at build time: (path relative to `blueprints/` with
/// forward slashes, file text), ascending by path. Generated by `build.rs`.
pub static STOCK_FILES: &[(&str, &str)] = include!(concat!(env!("OUT_DIR"), "/stock_files.rs"));

/// Stock ships: every `.bp.ron` in [`STOCK_FILES`].
pub fn stock_blueprint_files() -> impl Iterator<Item = (&'static str, &'static str)> { STOCK_FILES.iter().copied().filter(|(p, _)| p.ends_with(".bp.ron")) }
/// Stock kits: every `.kit.ron` in [`STOCK_FILES`].
pub fn stock_kit_files() -> impl Iterator<Item = (&'static str, &'static str)> { STOCK_FILES.iter().copied().filter(|(p, _)| p.ends_with(".kit.ron")) }

/// RON options every loader uses: default extensions plus implicit `Some` so optional fields read cleanly.
pub fn ron_options() -> ron::Options { ron::Options::default().with_default_extension(ron::extensions::Extensions::IMPLICIT_SOME) }

/// Parse embedded or trusted RON into a data type. Untrusted blueprint text goes through
/// [`crate::blueprint::io::load_blueprint`] instead (limits, migrations).
pub fn parse_ron<T: serde::de::DeserializeOwned>(text: &str, file: &str) -> ContentResult<T> {
    ron_options().from_str(text).map_err(|e| ContentError::Parse { file: file.to_string(), message: e.to_string() })
}
