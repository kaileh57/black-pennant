//! The Meridian Combine's Act 3 classes as editor build sheets (DESIGN.md L756-758, L866-875, L451, L551).
//!
//! Fourteen classes for Hollin, where the player's cap rises to 900 t. Act 3 commits at least 3,600 t per player
//! in five hulls, so the Combine's line runs from 600 t corvettes through 1,000 t frigates to 1,500 t destroyers,
//! every one under the 90 m capital line except the Liquidator's cruiser. Heavy guns (130 to 155 mm) arrive on
//! the gun frigates, destroyers and the cruiser; the two submarine classes are the AI-only boats the act brings.
//! Every combatant carries the stock fire-control chain its weapons need, its own power, fuel, crew and pumps;
//! hulls over 70 m run four screws and the cruiser six.
//!
//! Submarines are built the same way as every other class (a lofted, decked, bulkheaded shell): a round-bilged
//! hull with a low freeboard, a narrow sail, diesel-electric drive (generator, battery and electric motor on one
//! screw), hull sonar and heavy torpedo tubes. They are flagged `submersible` in their class rows, which makes the
//! hydro unit hold the depth their captains order (L451). The Tontine is the act's reference submarine for the
//! depth-charge gate (L618).
//!
//! The warships sit upright. Their hulls are an even number of cells wide, so a centred item of odd width lands
//! half a cell to starboard, and left there the heavy mounts, engines and launchers listed the warships 1 to 4
//! degrees on sim-core's hydrostatics. The heaviest such items are shifted half a cell to port (`.dz(-1)`) until
//! the transverse centre of mass sits within about a centimetre of the centreline, as a designer trims out a list
//! (`print_list_trim_act3` in `combine_act3.rs` lists the candidates). The batch-2 corvette was widened from 10.2
//! to 10.8 m to carry its 130 mm: at 10.2 m it had 0.42 m of GM. `combine_act3.rs` checks the offset, and
//! `crates/sim-systems/tests/hydrostatics_act3.rs` checks heel, GM and range of stability on the editor's float
//! gauge.
//!
//! Naming follows the earlier sheets: Combine warship classes carry ledger terms (Pledge, Collateral, Annuity,
//! Dividend, Equity, and Tontine and Accrual for the boats), merchants and civilians plain type names, and ace
//! ships a single word.
use super::builder::*;
use content::cell::ArmourTier;

const fn t(x: f64) -> At { At::Top(x) }
const fn hold(x: f64) -> At { At::Hold(x) }
const fn inside(x: f64) -> At { At::InHouse(x) }
const fn port(x: f64) -> At { At::Edge(x, Side::Port) }
const fn stbd(x: f64) -> At { At::Edge(x, Side::Starboard) }
/// Vertical launcher cells sunk through the weather deck.
const fn vls(x: f64) -> At { At::Flush(x) }

/// Twin screws and rudders under the transom, mirrored about the centreline (as the earlier sheets).
const TWIN: [Fit; 4] = [part("prop.small", At::Stern(2)).dz(-3), part("prop.small", At::Stern(2)).dz(2), part("rudder.small", At::Stern(0)).dz(-3), part("rudder.small", At::Stern(0)).dz(2)];
/// Four screws for the hulls over 70 m (each small screw absorbs 3.5 MW) and twin rudders behind the inner pair.
const QUAD: [Fit; 6] = [
    part("prop.small", At::Stern(2)).dz(-7), part("prop.small", At::Stern(2)).dz(-3), part("prop.small", At::Stern(2)).dz(2), part("prop.small", At::Stern(2)).dz(6),
    part("rudder.small", At::Stern(0)).dz(-3), part("rudder.small", At::Stern(0)).dz(2),
];
/// Six screws for the cruiser: 21 MW of absorption. Its long raked transom lifts the last metre of the run clear
/// of the water at the cruiser's float, so screws and rudders sit a metre further forward than on the frigates.
const SIX: [Fit; 8] = [
    part("prop.small", At::Stern(4)).dz(-11), part("prop.small", At::Stern(4)).dz(-7), part("prop.small", At::Stern(4)).dz(-3),
    part("prop.small", At::Stern(4)).dz(2), part("prop.small", At::Stern(4)).dz(6), part("prop.small", At::Stern(4)).dz(10),
    part("rudder.small", At::Stern(2)).dz(-3), part("rudder.small", At::Stern(2)).dz(2),
];
/// A submarine's single screw on the centreline with its rudder behind it.
const SINGLE: [Fit; 2] = [part("prop.small", At::Stern(2)).dz(-1), part("rudder.small", At::Stern(0))];

