//! The Meridian Combine's Act 2 classes as editor build sheets (DESIGN.md L756-758, L866-875).
//!
//! Thirteen classes for Corran Sound, where the player's cap rises to 400 t. Act 2 commits at least 1,600 t per
//! player in five hulls, so the Combine brings bigger ships: 50 to 58 m corvettes of 300 to 450 t, 74 m frigates
//! and an 84 m helicopter frigate, all under the 90 m capital line. Every combatant carries the stock
//! fire-control chain its weapons need, its own power, fuel, crew and pumps; hulls over 70 m run four screws.
//! The Act 1 hulls stay in service beside them, so Act 2 fleets mix both lists.
//!
//! Naming follows the Act 1 sheets: Combine warship classes carry ledger terms (Coupon, Warrant, Indenture,
//! Premium, Bond, Mortgage), merchants and civilians plain type names, and ace ships a single word.
//!
//! The warships sit upright. Their hulls are an even number of cells wide, so a centred item of odd width lands
//! half a cell to starboard, and left there a warship's engines, guns and launchers listed it 1 to 16 degrees on
//! sim-core's hydrostatics. The heaviest such items are shifted half a cell to port (`.dz(-1)`) until the
//! transverse centre of mass sits within about a centimetre of the centreline, as a designer trims out a list. The
//! aviso (8.4 m) and the batch-2 frigate (12.2 m) were widened until they were no longer tender. `combine_act2.rs`
//! checks the offset, and `crates/sim-systems/tests/hydrostatics_act2.rs` checks heel, GM and range of stability
//! on the editor's float gauge.
use super::builder::*;
use content::cell::{ArmourTier, Material};

const fn t(x: f64) -> At { At::Top(x) }
const fn hold(x: f64) -> At { At::Hold(x) }
const fn inside(x: f64) -> At { At::InHouse(x) }
const fn port(x: f64) -> At { At::Edge(x, Side::Port) }
const fn stbd(x: f64) -> At { At::Edge(x, Side::Starboard) }
/// Vertical launcher cells sunk through the weather deck.
const fn vls(x: f64) -> At { At::Flush(x) }

/// Twin screws and rudders under the transom, mirrored about the centreline (as the Act 1 sheets).
const TWIN: [Fit; 4] = [part("prop.small", At::Stern(2)).dz(-3), part("prop.small", At::Stern(2)).dz(2), part("rudder.small", At::Stern(0)).dz(-3), part("rudder.small", At::Stern(0)).dz(2)];
/// Four screws for the hulls over 70 m (each small screw absorbs 3.5 MW) and twin rudders behind the inner pair.
const QUAD: [Fit; 6] = [
    part("prop.small", At::Stern(2)).dz(-7), part("prop.small", At::Stern(2)).dz(-3), part("prop.small", At::Stern(2)).dz(2), part("prop.small", At::Stern(2)).dz(6),
    part("rudder.small", At::Stern(0)).dz(-3), part("rudder.small", At::Stern(0)).dz(2),
];

