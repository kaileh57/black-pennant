//! The Meridian Combine's Act 4 classes as editor build sheets (DESIGN.md L756-758, L866-875, L126, L533).
//!
//! Fourteen classes for the Meridian Roads, the Combine's home waters, where the player's cap rises to 1,800 t.
//! Act 4 commits at least 7,200 t per player (L747) in five hulls, about 1,440 t a hull, so the line runs from
//! 500 to 900 t corvettes through 1,500 t frigates to 2,000 t destroyers, every one at 90 m or under, and two capitals
//! over 90 m (L126, L533): a 128 m heavy cruiser and the Chairman's 150 m flagship, the largest hull the
//! enemy-class editor allows. The weight comes the way it does in a real yard: wider, deeper hulls, 40 and 80 mm
//! belts over the magazines and machinery, more guns and a heavier plant. Every combatant carries the stock
//! fire-control chain its weapons need, its own power, fuel, crew and pumps; the corvettes run four small screws
//! (14 MW of absorption), the 88 to 90 m hulls six (21 MW) and the capitals eight (28 MW).
//!
//! The Act 4 parts (twin 130 mm turret, large surface-to-air launcher, long-range search radar, gas-turbine
//! generator) arrive on the frigates, destroyers and capitals. The submarines stay Act 3's: no Act 4 boat is built.
//!
//! Naming follows the earlier sheets: Combine warship classes carry ledger terms (Surety, Option, Debenture,
//! Yield, Escrow, Margin, Consol, Principal), merchants and civilians plain type names, and the ace ship a single
//! word.
use super::builder::*;
