const fn t(x: f64) -> At { At::Top(x) }
const fn hold(x: f64) -> At { At::Hold(x) }
const fn inside(x: f64) -> At { At::InHouse(x) }
const fn port(x: f64) -> At { At::Edge(x, Side::Port) }
