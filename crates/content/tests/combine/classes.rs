//! The Meridian Combine's Act 1 classes as editor build sheets (DESIGN.md L756-758, L866-875).
//!
//! Twenty-one classes in five tiers. Combat tonnage climbs from a 15 t harbour launch to an 800 t frigate, so an
//! Act 1 task group of five meets the 600 t commitment floor with corvettes and gunboats, never by sending
//! the frigates everywhere. Every class carries the stock fire-control chain its weapons need (radar mast with
//! a director, or a director-less autocannon), its own power, fuel, crew and pumps, and twin screws above 20 m
//! (and on the launch, whose single centred screw sat half a cell off the centreline and listed it).
//!
//! Every class keeps a range of stability past Fit Check's 45 degree bar (`sim-systems/tests/seakeeping.rs`).
//! Where a sheet missed it, the centre of mass came down the way a yard would bring it down: heavy machinery
//! and tanks on the bottom rather than on a flat, top weight off the house roof, a light alloy superstructure,
//! a little more beam, and fixed ballast low amidships last.
//!
//! Naming: Combine warship classes are named for ledger terms (Tally, Levy, Ledger, Charter); merchant and
//! civilian hulls carry plain type names. Batch-2 variants are the heavier hulls the operation generator swaps
//! in for co-op and for the "use variants" doctrine cards (L834).
use super::builder::*;
